"""ACTUAL pymcprotocol 0.3.0 Type3E integration; never run against physical PLC.

Executed only with SHA-verified wheel injected by scripts.m10_wheel_gate.
Do not promote these CASE-IDs on skip / missing distribution / unsigned wheel.
"""
import importlib.metadata
import json
import os
from pathlib import Path
import struct
import threading

import pytest
from virtual_plc.server import Server

ROOT = Path(__file__).resolve().parents[2]
GOLDENS = {x['id']: bytes.fromhex(x['request_hex']) for x in json.loads(
    (ROOT/'suite/fixtures/wire_vectors_baseline.json').read_text())}


def live_client():
    if os.environ.get('VIRTUALPLC_RUN_PYMC') != '1':
        pytest.skip('real wheel was not installed and hash-verified')
    assert importlib.metadata.version('pymcprotocol') == '0.3.0'
    import pymcprotocol
    return pymcprotocol.Type3E()


def transaction(kind, *, golden=False):
    client = live_client()
    server = Server(('127.0.0.1', 0))
    worker = threading.Thread(target=server.serve_forever,
                              kwargs={'poll_interval': 0.01}, daemon=True)
    worker.start()
    captured = []
    try:
        client.connect('127.0.0.1', server.server_address[1])
        original = client._send  # pinned 0.3.0 internal API; captures actual generated bytes
        def record_send(packet):
            captured.append(bytes(packet))
            return original(packet)
        client._send = record_send
        if kind == 'D':
            values = [0x1995, 0x1202, 0x1130]
            client.batchwrite_wordunits('D100', values)
            observed = client.batchread_wordunits('D100', 3)
            if golden:
                assert captured == [GOLDENS['VEC002'], GOLDENS['VEC001']]
        else:
            values = [1, 0, 1, 0, 1]
            client.batchwrite_bitunits('M10', values)
            observed = client.batchread_bitunits('M10', 5)
            if golden:
                assert captured[0] == GOLDENS['VEC003']
        assert observed == values
        assert len(captured) == 2
        assert all(x[:2] == b'\x50\x00' for x in captured)
    finally:
        try:
            client.close()
        finally:
            server.shutdown()
            server.server_close()
            worker.join(timeout=3)
            assert not worker.is_alive()


@pytest.mark.parametrize('case_id,kind,golden', [
    ('CASE-0027', 'D', False), ('CASE-0109', 'D', False),
    ('CASE-0028', 'M', False), ('CASE-0110', 'M', False),
    ('CASE-0029', 'D', True), ('CASE-0111', 'M', True),
])
def test_real_pymc_030(record_property, case_id, kind, golden):
    # Attach CASE-ID only after a genuine wheel has been verified and executed.
    transaction(kind, golden=golden)
    record_property('case_id', case_id)
